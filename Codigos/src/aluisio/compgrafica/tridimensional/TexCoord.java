package aluisio.compgrafica.tridimensional;

public class TexCoord {
	private float u;
	private float v;
	
	public TexCoord(float u, float v) {
		this.u = u;
		this.v = v;
	}
	
	
	public float getU() {
		return u;
	}
	public void setU(float u) {
		this.u = u;
	}
	public float getV() {
		return v;
	}
	public void setV(float v) {
		this.v = v;
	}
	
	
}
